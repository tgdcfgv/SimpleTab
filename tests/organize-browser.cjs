const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true, channel:'chrome'});
  try {
    const context = await browser.newContext({viewport:{width:1440,height:1000}});
    await context.route('https://**/*', route => route.abort());
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(process.env.SIMTAB_TEST_URL || 'http://127.0.0.1:8091/newtab.html');
    await page.waitForFunction(() => !document.querySelector('.app-container').inert);
    const groups = () => page.evaluate(async () => JSON.parse(JSON.stringify((await import('./js/storage.js')).appData.groups)));
    const original = await groups();
    await page.click('#settingsBtn');
    await page.click('[data-settings-panel="settingsAbout"]');
    for (const browser of ['edge','chrome','safari']) {
      await page.click(`[data-guide="${browser}"]`);
      assert.equal(await page.locator(`[data-guide="${browser}"]`).getAttribute('aria-pressed'), 'true');
      assert.match(await page.locator('#migrationGuide').innerText(), /HTML/);
    }
    await page.click('#guideImportBtn', {trial:true});
    await page.setInputFiles('#bookmarkFile', {name:'safari.html',mimeType:'text/html',buffer:Buffer.from('<DL><DT><A HREF="https://example.org/import">迁移书签</A></DL>')});
    await page.waitForFunction(() => document.querySelector('#bulkEditorDialog').open);
    assert.deepEqual(await groups(),original);
    assert.equal(await page.locator('.bulk-outline-group').last().locator('[data-key]').count(),1);
    await page.click('#bulkSave');
    await page.waitForFunction(() => document.querySelector('#guideImportStatus').textContent.includes('已导入并保存'));
    await page.click('[data-settings-panel="settingsContent"]');
    await page.selectOption('#groupColumnsSelect', '2', {force:true});
    assert.equal(await page.locator('#groupsContainer > .group-col').count(), 2);
    await page.reload();
    await page.waitForFunction(() => !document.querySelector('.app-container').inert);
    assert.equal(await page.locator('#groupsContainer > .group-col').count(), 2);
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(() => document.querySelectorAll('#groupsContainer > .group-col').length === 1);
    await page.setViewportSize({width:1440,height:1000});
    await page.waitForFunction(() => document.querySelectorAll('#groupsContainer > .group-col').length === 2);
    await page.click('#settingsBtn'); await page.click('[data-settings-panel="settingsContent"]');
    await page.click('#openBulkEditor');
    assert.equal(await page.locator('.bulk-outline-group').count(),original.length + 1);
    const firstGroup = page.locator('.bulk-outline-group').first();
    await firstGroup.locator('[data-select-group]').check();
    assert.equal(await firstGroup.locator('[data-key]:checked').count(),original[0].links.length);
    await firstGroup.locator('[data-key]').first().uncheck();
    assert.equal(await firstGroup.locator('[data-select-group]').evaluate(el => el.indeterminate),true);
    await page.click('#bulkCollapseAll');
    assert.equal(await page.locator('.bulk-group-children:visible').count(),0);
    assert.match(await page.locator('#bulkSelectionCount').innerText(),new RegExp(`已选 ${original[0].links.length-1}`));
    await firstGroup.locator('.bulk-fold').click();
    assert.equal(await firstGroup.locator('.bulk-group-children').isVisible(),true);
    await firstGroup.locator('[data-select-group]').check();
    await firstGroup.locator('[data-select-group]').uncheck();
    await page.click('#bulkExpandAll');
    await page.fill('#bulkSearch',original[1].name);
    assert.equal(await page.locator('.bulk-outline-group').count(),1);
    assert.equal(await page.locator('#bulkSiteList [data-key]').count(),original[1].links.length);
    await page.fill('#bulkSearch','');
    await page.locator('#bulkSiteList [data-key]').first().check();
    await page.selectOption('#bulkMoveTarget','1'); await page.click('#bulkMove');
    assert.deepEqual((await groups()).slice(0,original.length),original);
    await page.click('#bulkSave');
    await page.waitForFunction(() => !document.querySelector('#bulkEditorDialog').open);
    let after = await groups();
    assert.equal(after[0].links.length,original[0].links.length-1);
    assert.equal(after[1].links.at(-1).id,original[0].links[0].id);
    await page.click('#openBulkEditor');
    await page.fill('#bulkSearch',original[0].links[1].title);
    await page.check('#bulkSelectAll'); await page.click('#bulkDelete');
    await page.click('#bulkClose');
    assert.deepEqual(await groups(),after);
    await page.click('#openBulkEditor');
    await page.fill('#bulkSearch',original[0].links[1].title);
    await page.check('#bulkSelectAll'); await page.click('#bulkDelete'); await page.click('#bulkSave');
    await page.waitForFunction(() => !document.querySelector('#bulkEditorDialog').open);
    assert.equal((await groups())[0].links.length,original[0].links.length-2);
    await page.click('#openBulkEditor');
    for (const width of [390,768,1440]) {
      await page.setViewportSize({width,height:900});
      assert.equal(await page.locator('#bulkEditorDialog').evaluate(el => el.scrollWidth > el.clientWidth + 1),false,`bulk overflow ${width}`);
      await page.screenshot({path:`/tmp/simtab-bulk-${width}.png`,animations:'disabled'});
    }
    await page.keyboard.press('Escape');
    await page.click('#closeSettingsBtn');
    const dragSurface = await page.evaluate(async () => {
      const {handleGroupDragStart,handleDragEnd} = await import('./js/drag.js');
      const card = document.querySelector('.group-card');
      const dataTransfer = new DataTransfer();
      const rect = card.getBoundingClientRect();
      handleGroupDragStart({target:card,currentTarget:card,dataTransfer,clientX:rect.left+20,clientY:rect.top+20});
      const result = {filter:getComputedStyle(card).backdropFilter,bg:getComputedStyle(card).backgroundColor,data:dataTransfer.getData('text/plain')};
      handleDragEnd(); return result;
    });
    assert.equal(dragSurface.filter,'none');
    assert.match(dragSurface.bg,/^rgb\(/);
    assert(dragSurface.data);
    await page.locator('#groupsContainer').click({button:'right',position:{x:2,y:2}});
    await page.click('#contextBulkEditor');
    const activeSpace = await page.evaluate(async () => (await import('./js/storage.js')).appData.activeSpaceId);
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(async () => (await import('./js/storage.js')).appData.activeSpaceId), activeSpace);
    assert.equal(await page.locator('#bulkEditorDialog').evaluate(el => el.contains(document.activeElement)),true);
    await page.keyboard.press('Escape');
    await page.click('#settingsBtn');await page.click('[data-settings-panel="settingsAbout"]');
    await page.screenshot({path:'/tmp/simtab-help.png',animations:'disabled'});
    await page.emulateMedia({colorScheme:'dark'});
    await page.click('#helpBulkEditor');
    assert.equal(await page.locator('#bulkEditorDialog').evaluate(el => getComputedStyle(el).backgroundColor),'rgb(30, 30, 32)');
    await page.screenshot({path:'/tmp/simtab-bulk-dark.png',animations:'disabled'});
    await page.keyboard.press('Escape');
    // Folder paths and unsafe URL handling survive import preview without writes.
    const beforeImport = await groups();
    const fixture = '<DL><p><DT><H3>书签栏</H3><DL><p><DT><H3>设计</H3><DL><p><DT><A HREF="https://example.org/design">设计工具</A><DT><A HREF="javascript:alert(1)">unsafe</A></DL></DL></DL>';
    const parsed = await page.evaluate(async html => (await import('./js/extension.js')).parseBookmarkGroups(html),fixture);
    assert.equal(parsed[0].name,'书签栏 / 设计');
    assert.equal(parsed[0].links.length,1);
    await page.click('#helpBulkEditor');
    const chooserReady = page.waitForEvent('filechooser');
    await page.click('#bulkImportBookmarks');
    const chooser = await chooserReady;
    await chooser.setFiles({name:'folders.html',mimeType:'text/html',buffer:Buffer.from(fixture)});
    await page.waitForFunction(() => document.querySelector('#bulkEditStatus').textContent.includes('folders.html'));
    assert.match(await page.locator('.bulk-outline-group').last().innerText(),/书签栏 \/ 设计/);
    assert.deepEqual(await groups(),beforeImport);
    await page.click('#bulkClose');
    assert.deepEqual(await groups(),beforeImport);
    assert.match(await page.locator('#guideImportStatus').innerText(),/已取消导入/);
    assert.deepEqual(errors,[]);
    console.log('PASS: browser guides and import feedback, saved columns and responsive fallback, staged bulk move/delete/cancel, mobile layout, drag surface cleanup.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
